#!/usr/bin/env bun
/**
 * Emit `dist/sw.js`: an app-shell service worker that precaches the built client so
 * the installed app opens offline. Runs after `bun build` and build-assets.ts (see the `build` script).
 *
 * The cache name is derived from the precached file names and sizes. Bundles are
 * content-hashed, so any deploy that changes the client changes `sw.js`, which is
 * how browsers notice an update. The new worker installs the new shell and drops the
 * old cache. All URLs are relative, so the build works under a path prefix (GitHub
 * Pages project sites).
 *
 * Navigations go to the network first (falling back to the cached shell after
 * {@link NAVIGATE_TIMEOUT_MS} or offline), so a launch while online always runs the
 * current deploy even when the worker's own update is late. Precaching and
 * navigations bypass the HTTP cache: GitHub Pages serves `index.html` with
 * `max-age=600`, and a stale copy would pin the previous bundle into the new shell.
 * Requests made with `cache: "no-store"` (the app's own update check) pass through.
 *
 * The diagram engines (Mermaid, Excalidraw) and Excalidraw's fonts (`excalidraw-assets/`) are not
 * precached: the worker caches them on first use, so diagrams work offline after being shown once.
 *
 * It also shows the companion's Web Push notifications (see scripts/companion.ts):
 * a payload's `badge` sets the app icon badge, `reply` adds an inline text-reply action,
 * and a tap routes to the session or to the payload's `open` route. An open window gets
 * an `open-session`, `open-route` or `notification-reply` message, otherwise the app
 * launches with `#open:<instanceId>[&reply=<text>]` or `#<route>`.
 */
import * as fs from "node:fs";
import * as path from "node:path";

const dist = path.join(import.meta.dir, "..", "dist");

/** Site-root files the client never fetches; skipping them keeps the install small. */
const SKIP: Record<string, true> = { "sw.js": true, "og-image.png": true, "robots.txt": true, "sitemap.xml": true };
/** How long a launch waits for the network before opening the cached shell. */
const NAVIGATE_TIMEOUT_MS = 3_000;

/**
 * Output files only the diagram engines load (Mermaid, Excalidraw and what only they share), from the bundler's
 * metafile: they total several MB, so they are fetched when a diagram is first drawn instead of at install.
 * Files the rest of the app also reaches (the entry, other lazy sheets and their shared chunks) stay precached.
 */
function diagramOnlyFiles(): Set<string> {
	const metaPath = path.join(dist, ".meta.json");
	const meta: { outputs: Record<string, { entryPoint?: string; imports: { path: string }[] }> } = JSON.parse(
		fs.readFileSync(metaPath, "utf8"),
	);
	fs.rmSync(metaPath);
	const engines = Object.entries(meta.outputs)
		.filter(
			([, info]) =>
				info.entryPoint === "src/lib/mermaid-engine.ts" || info.entryPoint === "src/lib/excalidraw-engine.ts",
		)
		.map(([output]) => output);
	/** Every output reachable from `roots` without entering a `blocked` one. */
	const reach = (roots: readonly string[], blocked: ReadonlySet<string>): Set<string> => {
		const seen = new Set<string>();
		const visit = (output: string): void => {
			if (seen.has(output) || blocked.has(output)) return;
			seen.add(output);
			for (const next of meta.outputs[output]?.imports ?? []) visit(next.path);
		};
		for (const root of roots) visit(root);
		return seen;
	};
	// Chunks the bundler splits out of a package's own dynamic imports have entry points too; the app's roots are its sources and the page.
	const others = Object.entries(meta.outputs)
		.filter(([output, info]) => {
			const entry = info.entryPoint;
			return (
				entry !== undefined && !engines.includes(output) && (entry === "index.html" || entry.startsWith("src/"))
			);
		})
		.map(([output]) => output);
	const rest = reach(others, new Set(engines));
	const lazy = new Set<string>();
	for (const output of reach(engines, new Set())) {
		if (!rest.has(output)) lazy.add(output.replace(/^\.\//, ""));
	}
	return lazy;
}

const lazyFiles = diagramOnlyFiles();
const files: string[] = [];
const fingerprint = new Bun.CryptoHasher("sha256");
for (const name of [...new Bun.Glob("*").scanSync({ cwd: dist, onlyFiles: true })].sort()) {
	if (SKIP[name]) continue;
	fingerprint.update(`${name}:${Bun.file(path.join(dist, name)).size}\n`);
	if (!lazyFiles.has(name)) files.push(name);
}
if (!files.includes("index.html")) {
	console.error("build-sw: dist/index.html missing; run the bundle step first");
	process.exit(1);
}
const version = fingerprint.digest("hex").slice(0, 12);

const sw = `// Auto-generated by packages/collab-web/scripts/build-sw.ts - DO NOT EDIT
const CACHE = "omp-collab-${version}";
const SHELL = ${JSON.stringify(["./", ...files.map(f => `./${f}`)])};

self.addEventListener("install", event => {
	event.waitUntil(
		caches
			.open(CACHE)
			.then(cache => cache.addAll(SHELL.map(url => new Request(url, { cache: "reload" }))))
			.then(() => self.skipWaiting()),
	);
});

self.addEventListener("activate", event => {
	event.waitUntil(
		caches
			.keys()
			.then(keys => Promise.all(keys.filter(k => k.startsWith("omp-collab-") && k !== CACHE).map(k => caches.delete(k))))
			.then(() => self.clients.claim()),
	);
});

function cachedShell() {
	return caches.open(CACHE).then(cache => cache.match("./"));
}

/** The current shell from the network, refreshing the cached copy; the cached shell when slow or offline. */
function navigate() {
	const network = fetch(new Request("./", { cache: "no-cache" })).then(res => {
		if (!res.ok) throw new Error("shell " + res.status);
		const copy = res.clone();
		caches.open(CACHE).then(cache => cache.put("./", copy));
		return res;
	});
	// Offline answers at once from the cache.
	const settled = network.catch(() => cachedShell().then(hit => hit || Response.error()));
	// A slow network gives way to the cached shell; with nothing cached it is waited out.
	// Executor form: Promise.withResolvers is missing from the older iOS WebKit this must run on.
	const slow = new Promise(resolve => setTimeout(resolve, ${NAVIGATE_TIMEOUT_MS}))
		.then(cachedShell)
		.then(hit => hit || settled);
	return Promise.race([settled, slow]);
}

const BASE_PATH = new URL("./", self.location).pathname;

/**
 * Build output fetched after install and cached on first use, so diagrams work offline once shown: the hashed
 * scripts, styles and fonts at the site root and Excalidraw's own files. Query-less only: a URL with a query is never
 * stored (nothing else is cached for it), which also keeps the cache to the files this build ships.
 */
function isRuntimeAsset(url) {
	if (url.search !== "" || !url.pathname.startsWith(BASE_PATH)) return false;
	const rel = url.pathname.slice(BASE_PATH.length);
	if (rel.startsWith("excalidraw-assets/")) return true;
	return !rel.includes("/") && (rel.endsWith(".js") || rel.endsWith(".css") || rel.endsWith(".woff2"));
}

self.addEventListener("fetch", event => {
	const req = event.request;
	if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin || req.cache === "no-store") return;
	// Navigations (including share-target URLs with a query) all get the shell; the
	// room link lives in the fragment, which never reaches the worker.
	if (req.mode === "navigate") {
		event.respondWith(navigate());
		return;
	}
	const url = new URL(req.url);
	if (isRuntimeAsset(url)) {
		event.respondWith(
			caches.open(CACHE).then(async cache => {
				const hit = await cache.match(req);
				if (hit) return hit;
				const res = await fetch(req);
				// Only whole successful answers: a partial (206) one cannot be stored, and an error must not stick.
				if (res.status === 200 && res.type === "basic") await cache.put(req, res.clone());
				return res;
			}),
		);
		return;
	}
	event.respondWith(caches.open(CACHE).then(cache => cache.match(req, { ignoreSearch: true })).then(hit => hit || fetch(req)));
});

/** Set the app icon badge to the pushed count, clearing it at 0; a no-op where the Badging API is missing. */
function setBadge(count) {
	const nav = self.navigator;
	try {
		if (count > 0 && nav.setAppBadge) return nav.setAppBadge(count).catch(() => {});
		if (count === 0 && nav.clearAppBadge) return nav.clearAppBadge().catch(() => {});
	} catch {}
	return Promise.resolve();
}

self.addEventListener("push", event => {
	let data = {};
	try {
		data = event.data ? event.data.json() : {};
	} catch {}
	const title = typeof data.title === "string" ? data.title : "omp collab";
	const instanceId = typeof data.instanceId === "string" ? data.instanceId : null;
	const options = {
		body: typeof data.body === "string" ? data.body : "",
		icon: "./favicon-192x192.png",
		tag: typeof data.tag === "string" ? data.tag : instanceId || "omp-collab",
		data: {
			instanceId,
			url: typeof data.url === "string" && /^https:\\/\\//.test(data.url) ? data.url : null,
			open: typeof data.open === "string" && /^[a-z][a-z0-9-]*:./.test(data.open) ? data.open : null,
		},
	};
	// An inline text reply where the platform supports it (Chrome on Android and desktop);
	// elsewhere the action shows as a plain button, and iOS shows no actions at all.
	if (data.reply === true && instanceId) {
		options.actions = [
			{ action: "reply", type: "text", title: "Reply", placeholder: "Message the agent\\u2026" },
			{ action: "open", title: "Open" },
		];
	}
	const badge = typeof data.badge === "number" && data.badge >= 0 ? Math.floor(data.badge) : null;
	event.waitUntil(
		Promise.all([self.registration.showNotification(title, options), badge === null ? null : setBadge(badge)]),
	);
});

self.addEventListener("notificationclick", event => {
	event.notification.close();
	const info = event.notification.data || {};
	const instanceId = info.instanceId;
	if (info.url) {
		event.waitUntil(self.clients.openWindow(info.url));
		return;
	}
	const text = event.action === "reply" && typeof event.reply === "string" ? event.reply.trim() : "";
	// A typed reply goes to its session; otherwise the route the notice names, else its session.
	const replying = text !== "" && !!instanceId;
	const route = replying
		? "open:" + instanceId + "&reply=" + encodeURIComponent(text)
		: info.open || (instanceId ? "open:" + instanceId : null);
	event.waitUntil(
		self.clients.matchAll({ type: "window", includeUncontrolled: true }).then(windows => {
			const win = windows[0];
			if (win) {
				if (replying) win.postMessage({ t: "notification-reply", instanceId, text });
				else if (info.open) win.postMessage({ t: "open-route", route: info.open });
				else if (instanceId) win.postMessage({ t: "open-session", instanceId });
				return win.focus();
			}
			return self.clients.openWindow(route ? "./#" + route : "./");
		}),
	);
});
`;

await Bun.write(path.join(dist, "sw.js"), sw);
console.log(`build-sw: dist/sw.js (${files.length} files, cache omp-collab-${version})`);
